_pool = None


class Row:
    """Wiersz z PostgreSQL działający jak sqlite3.Row: row[0], row["kolumna"], row.keys()."""
    __slots__ = ("_index", "_values")

    def __init__(self, index, values):
        self._index, self._values = index, values

    def __getitem__(self, key):
        return self._values[key if isinstance(key, int) else self._index[key]]

    def __iter__(self):
        return iter(self._values)

    def __len__(self):
        return len(self._values)

    def keys(self):
        return list(self._index)


def _row_factory(cursor):
    index = {c.name: i for i, c in enumerate(cursor.description or ())}
    return lambda values: Row(index, values)


@functools.lru_cache(maxsize=1024)
def _to_postgres(sql, named):
    sql = sql.replace("%", "%%")
    if named:
        return re.sub(r"(?<!:):([A-Za-z_]\w*)", r"%(\1)s", sql)
    return sql.replace("?", "%s")


def _configure(conn):
    """Każde nowe połączenie z puli: tabele gry w schemacie DB_SCHEMA (jeśli ustawiony)."""
    if DB_SCHEMA:
        conn.execute(f"CREATE SCHEMA IF NOT EXISTS {DB_SCHEMA}")
        conn.execute(f"SET search_path TO {DB_SCHEMA}")
    conn.commit()


class Connection:
    def __init__(self, raw, pg):
        self.raw, self.pg = raw, pg

    def execute(self, sql, params=()):
        if not self.pg:
            return self.raw.execute(sql, params)
        if not params:
            return self.raw.execute(sql)
        return self.raw.execute(_to_postgres(sql, isinstance(params, dict)), params)

    def executescript(self, script):
        if self.pg:
            self.raw.execute(script)  # PostgreSQL przyjmuje kilka poleceń naraz, gdy nie ma parametrów
        else:
            self.raw.executescript(script)

    def lock_users(self, *user_ids):
        """Blokuje graczy do końca transakcji - dwa równoległe zapytania tego samego gracza
        (np. szybkie podwójne kliknięcie) nie wydadzą tych samych pieniędzy ani kart dwa razy."""
        ids = sorted({int(i) for i in user_ids if i is not None})
        if not ids:
            return
        if self.pg:  # zawsze w tej samej kolejności (rosnące id), żeby dwie wymiany się nie zakleszczyły
            marks = ",".join("?" * len(ids))
            self.execute(f"SELECT id FROM users WHERE id IN ({marks}) ORDER BY id FOR UPDATE", ids).fetchall()
        elif not self.raw.in_transaction:
            self.raw.execute("BEGIN IMMEDIATE")  # SQLite: jeden zapisujący naraz w całej bazie

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()

    def close(self):
        if self.pg:
            if not self.raw.closed:
                self.raw.rollback()  # niezatwierdzone zmiany (błąd albo samo czytanie) nie wracają do puli
            _pool.putconn(self.raw)
        else:
            self.raw.close()


def connect(sqlite_path):
    """Nowe połączenie: z puli PostgreSQL (gdy ustawiono DATABASE_URL) albo z plikiem SQLite."""
    global _pool
    if USE_POSTGRES:
        if _pool is None:
            from psycopg_pool import ConnectionPool
            _pool = ConnectionPool(DATABASE_URL, min_size=1, max_size=int(os.environ.get("DB_POOL_SIZE", "10")),
                                   kwargs={"row_factory": _row_factory}, configure=_configure, open=True,
                                   check=ConnectionPool.check_connection)  # zerwane połączenia (restart serwera bazy)
        return Connection(_pool.getconn(), True)
    raw = sqlite3.connect(sqlite_path, timeout=10)
    raw.row_factory = sqlite3.Row
    return Connection(raw, False)


def describe(sqlite_path):
    """Opis bazy do wypisania przy starcie (bez hasła)."""
    if USE_POSTGRES:
        return "PostgreSQL " + re.sub(r"//[^@/]*@", "//", DATABASE_URL).split("?")[0] +             (f" (schemat {DB_SCHEMA})" if DB_SCHEMA else "")
    return "SQLite " + os.path.basename(sqlite_path)
