-- Schemat bazy PostgreSQL (ten sam co database.PG_SCHEMA w wersji Python) - wykonywany przy każdym starcie,
-- wszystko IF NOT EXISTS, więc istniejąca baza gry działa bez migracji. Nowa kolumna/tabela: dopisać tutaj.
CREATE TABLE IF NOT EXISTS state (key TEXT PRIMARY KEY, value BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id TEXT NOT NULL,
    holo INTEGER NOT NULL DEFAULT 0,
    created_at DOUBLE PRECISION NOT NULL,
    variant TEXT NOT NULL DEFAULT 'normal',
    user_id BIGINT,
    favorite INTEGER NOT NULL DEFAULT 0
);
-- kolumny dodane po pierwszym wdrożeniu (istniejąca baza na serwerze ich jeszcze nie ma)
ALTER TABLE items ADD COLUMN IF NOT EXISTS favorite INTEGER NOT NULL DEFAULT 0;
CREATE INDEX IF NOT EXISTS items_user ON items (user_id);
CREATE TABLE IF NOT EXISTS discovered (person_id TEXT PRIMARY KEY);
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    avatar TEXT NOT NULL DEFAULT '😎',
    is_admin INTEGER NOT NULL DEFAULT 0,
    created_at DOUBLE PRECISION NOT NULL,
    avatar_card TEXT NOT NULL DEFAULT '',
    avatar_variant TEXT NOT NULL DEFAULT 'normal',
    banned INTEGER NOT NULL DEFAULT 0,
    ban_reason TEXT NOT NULL DEFAULT '',
    ranking_hidden INTEGER NOT NULL DEFAULT 0,
    money_generated INTEGER NOT NULL DEFAULT 0
);
ALTER TABLE users ADD COLUMN IF NOT EXISTS ranking_hidden INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS money_generated INTEGER NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS admin_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at DOUBLE PRECISION NOT NULL,
    admin_id BIGINT, admin_name TEXT NOT NULL,
    action TEXT NOT NULL,
    target_id BIGINT, target_name TEXT NOT NULL DEFAULT '',
    details TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS admin_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL, body TEXT NOT NULL,
    starts_at DOUBLE PRECISION NOT NULL, ends_at DOUBLE PRECISION NOT NULL,
    created_at DOUBLE PRECISION NOT NULL, admin_name TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS admin_message_seen (message_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
                                               seen_at DOUBLE PRECISION NOT NULL, PRIMARY KEY (message_id, user_id));
CREATE UNIQUE INDEX IF NOT EXISTS users_username ON users (LOWER(username));
CREATE TABLE IF NOT EXISTS user_state (user_id BIGINT NOT NULL, key TEXT NOT NULL, value BIGINT NOT NULL,
                                       PRIMARY KEY (user_id, key));
CREATE TABLE IF NOT EXISTS user_discovered (user_id BIGINT NOT NULL, person_id TEXT NOT NULL,
                                            PRIMARY KEY (user_id, person_id));
CREATE TABLE IF NOT EXISTS user_collected (user_id BIGINT NOT NULL, person_id TEXT NOT NULL, variant TEXT NOT NULL,
                                           PRIMARY KEY (user_id, person_id, variant));
ALTER TABLE user_collected ADD COLUMN IF NOT EXISTS at DOUBLE PRECISION;
ALTER TABLE user_collected ADD COLUMN IF NOT EXISTS source TEXT;
CREATE TABLE IF NOT EXISTS daily_claims (user_id BIGINT NOT NULL, day TEXT NOT NULL, amount BIGINT NOT NULL,
                                         PRIMARY KEY (user_id, day));
CREATE TABLE IF NOT EXISTS friendships (requester_id BIGINT NOT NULL, addressee_id BIGINT NOT NULL,
                                        status TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL,
                                        PRIMARY KEY (requester_id, addressee_id));
CREATE TABLE IF NOT EXISTS showcase (user_id BIGINT NOT NULL, pos INTEGER NOT NULL, item_id BIGINT NOT NULL,
                                     PRIMARY KEY (user_id, pos));
CREATE TABLE IF NOT EXISTS trades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_id BIGINT NOT NULL, to_id BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending',
    message TEXT NOT NULL DEFAULT '',
    money_give BIGINT NOT NULL DEFAULT 0, money_want BIGINT NOT NULL DEFAULT 0,
    created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS trade_lines (
    trade_id BIGINT NOT NULL, side TEXT NOT NULL, item_id BIGINT,
    person_id TEXT NOT NULL, variant TEXT NOT NULL, count INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX IF NOT EXISTS trade_lines_trade ON trade_lines (trade_id);
CREATE TABLE IF NOT EXISTS crate_access (user_id BIGINT NOT NULL, crate_id TEXT NOT NULL,
                                         PRIMARY KEY (user_id, crate_id));
CREATE TABLE IF NOT EXISTS user_chests (user_id BIGINT NOT NULL, kind TEXT NOT NULL, count INTEGER NOT NULL,
                                        PRIMARY KEY (user_id, kind));
CREATE TABLE IF NOT EXISTS arena_daily (user_id BIGINT NOT NULL, day TEXT NOT NULL, wins INTEGER NOT NULL DEFAULT 0,
                                        PRIMARY KEY (user_id, day));
CREATE TABLE IF NOT EXISTS hall_of_fame (person_id TEXT NOT NULL, variant TEXT NOT NULL, first_user_id BIGINT,
                                         first_at DOUBLE PRECISION NOT NULL, source TEXT NOT NULL DEFAULT 'drop',
                                         drops INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (person_id, variant));
CREATE TABLE IF NOT EXISTS feed (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id BIGINT NOT NULL,
    to_user_id BIGINT,
    kind TEXT NOT NULL,
    person_id TEXT NOT NULL,
    variant TEXT NOT NULL,
    message TEXT NOT NULL DEFAULT '',
    created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS market_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL, item_id BIGINT NOT NULL, person_id TEXT NOT NULL, variant TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'fixed', price BIGINT NOT NULL, step BIGINT NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'active', buyer_id BIGINT, final_price BIGINT NOT NULL DEFAULT 0,
    created_at DOUBLE PRECISION NOT NULL, ends_at DOUBLE PRECISION, updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS market_listings_status ON market_listings (status);
CREATE TABLE IF NOT EXISTS market_offers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL, buyer_id BIGINT NOT NULL, price BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending', created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS market_offers_listing ON market_offers (listing_id);
CREATE TABLE IF NOT EXISTS market_bids (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL, bidder_id BIGINT NOT NULL, amount BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active', created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS market_bids_listing ON market_bids (listing_id);
CREATE TABLE IF NOT EXISTS market_wanted (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buyer_id BIGINT NOT NULL, person_id TEXT NOT NULL, variant TEXT NOT NULL, price BIGINT NOT NULL,
    status TEXT NOT NULL DEFAULT 'active', seller_id BIGINT,
    created_at DOUBLE PRECISION NOT NULL, updated_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS jackpots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creator_id BIGINT NOT NULL, invite_id BIGINT, joiner_id BIGINT,
    status TEXT NOT NULL DEFAULT 'open', value_a BIGINT NOT NULL DEFAULT 0, value_b BIGINT NOT NULL DEFAULT 0,
    winner_id BIGINT, roll DOUBLE PRECISION, created_at DOUBLE PRECISION NOT NULL, finished_at DOUBLE PRECISION,
    is_public INTEGER NOT NULL DEFAULT 1, ready_a INTEGER NOT NULL DEFAULT 0, ready_b INTEGER NOT NULL DEFAULT 0,
    updated_at DOUBLE PRECISION
);
ALTER TABLE jackpots ADD COLUMN IF NOT EXISTS is_public INTEGER NOT NULL DEFAULT 1;
ALTER TABLE jackpots ADD COLUMN IF NOT EXISTS ready_a INTEGER NOT NULL DEFAULT 0;
ALTER TABLE jackpots ADD COLUMN IF NOT EXISTS ready_b INTEGER NOT NULL DEFAULT 0;
ALTER TABLE jackpots ADD COLUMN IF NOT EXISTS updated_at DOUBLE PRECISION;
CREATE TABLE IF NOT EXISTS jackpot_invites (jackpot_id BIGINT NOT NULL, user_id BIGINT NOT NULL,
                                            PRIMARY KEY (jackpot_id, user_id));
CREATE TABLE IF NOT EXISTS jackpot_items (
    jackpot_id BIGINT NOT NULL, side TEXT NOT NULL, item_id BIGINT NOT NULL,
    person_id TEXT NOT NULL, variant TEXT NOT NULL, value BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS jackpot_items_jackpot ON jackpot_items (jackpot_id);
CREATE TABLE IF NOT EXISTS card_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token TEXT NOT NULL UNIQUE, person_id TEXT NOT NULL, note TEXT NOT NULL DEFAULT '',
    created_by BIGINT, created_at DOUBLE PRECISION NOT NULL, active INTEGER NOT NULL DEFAULT 1,
    max_uses INTEGER NOT NULL DEFAULT 0, uses INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS card_link_claims (link_id BIGINT NOT NULL, user_id BIGINT NOT NULL, item_id BIGINT,
                                             claimed_at DOUBLE PRECISION NOT NULL, PRIMARY KEY (link_id, user_id));
CREATE TABLE IF NOT EXISTS blackjack_games (
    user_id BIGINT PRIMARY KEY,
    item_ids TEXT NOT NULL, stake BIGINT NOT NULL,
    double_ids TEXT NOT NULL DEFAULT '[]', double_stake BIGINT NOT NULL DEFAULT 0,
    deck TEXT NOT NULL, player TEXT NOT NULL, dealer TEXT NOT NULL, created_at DOUBLE PRECISION NOT NULL
);
CREATE TABLE IF NOT EXISTS horse_bets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race BIGINT NOT NULL, user_id BIGINT NOT NULL, horse INTEGER NOT NULL,
    item_ids TEXT NOT NULL, stake BIGINT NOT NULL, status TEXT NOT NULL DEFAULT 'open',
    payout BIGINT NOT NULL DEFAULT 0, result TEXT NOT NULL DEFAULT '{}',
    seen INTEGER NOT NULL DEFAULT 0, created_at DOUBLE PRECISION NOT NULL,
    pays DOUBLE PRECISION NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS horse_bets_race ON horse_bets (race);
CREATE INDEX IF NOT EXISTS horse_bets_user ON horse_bets (user_id);
CREATE TABLE IF NOT EXISTS horse_settings (
    horse INTEGER PRIMARY KEY, name TEXT NOT NULL DEFAULT '', pays DOUBLE PRECISION NOT NULL DEFAULT 0
);

